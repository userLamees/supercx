"""Database models and session handling (SQLite locally, Postgres on Replit)."""
from datetime import date, datetime, timezone
from pathlib import Path
from typing import Optional
from uuid import uuid4

from sqlalchemy import inspect, text
from sqlmodel import Field, Session, SQLModel, create_engine

from .config import DATABASE_URL
from .schemas import CaseStatus


def _now() -> datetime:
    return datetime.now(timezone.utc)


class SupportCase(SQLModel, table=True):
    __tablename__ = "support_cases"

    id: str = Field(default_factory=lambda: str(uuid4()), primary_key=True)
    created_at: datetime = Field(default_factory=_now, index=True)
    updated_at: datetime = Field(default_factory=_now)
    question: str
    language: str
    contact: str
    tier_id: Optional[str] = Field(default=None, index=True)
    summary: Optional[str] = None
    status: CaseStatus = Field(default=CaseStatus.new, index=True)
    category: str = Field(default="inquiry", index=True)  # unanswered | inquiry | complaint | suggestion | service
    tracking_hash: str = ""                 # salted hash of the visitor's tracking code (code shown once)
    reply: Optional[str] = None             # the team's reply, visible to the visitor
    replied_at: Optional[datetime] = None
    replied_by: Optional[str] = None        # staff name, shown to staff only
    demo: bool = False                      # generated by app.seed_demo


class Notification(SQLModel, table=True):
    """A message to the visitor about their case (today: the team replied). The text holds the
    case number and a link only, never the reply itself or the tracking code."""
    __tablename__ = "notifications"

    id: str = Field(default_factory=lambda: str(uuid4()), primary_key=True)
    created_at: datetime = Field(default_factory=_now, index=True)
    case_id: str = Field(index=True)
    kind: str = "case.reply"                # case.reply | case.reply_update
    channel: str                            # email | whatsapp | none
    recipient: str = ""                     # masked (m***@example.com, +9665******12)
    status: str = Field(default="pending", index=True)  # pending | sent | simulated | failed | skipped
    subject: str = ""
    body: str = ""
    link: str = ""                          # "My requests" link with the case number
    error: Optional[str] = None             # short reason when failed or skipped
    sent_at: Optional[datetime] = None
    attempts: int = 0
    demo: bool = False                      # no provider configured: kept in the demo outbox


class CaseSync(SQLModel, table=True):
    """One attempt to send a case event to the association's system (webhook or email), or the
    demo outbox when no system is configured. Holds the payload sent, never a secret."""
    __tablename__ = "case_syncs"

    id: str = Field(default_factory=lambda: str(uuid4()), primary_key=True)
    created_at: datetime = Field(default_factory=_now, index=True)
    case_id: str = Field(index=True)
    event: str                              # case.created | case.replied | case.status
    target: str                             # webhook | email | demo
    status: str = Field(default="pending", index=True)  # pending | sent | simulated | failed
    payload: str = ""                       # JSON sent (redacted text, contact only with consent)
    external_id: Optional[str] = None       # the association system's id for the case, if returned
    error: Optional[str] = None
    attempts: int = 0
    sent_at: Optional[datetime] = None
    demo: bool = False


class WhatsAppConversation(SQLModel, table=True):
    """The running WhatsApp conversation with one number, so the assistant keeps context.
    The number is stored only as a hash; the recent turns are kept for a short time
    (WHATSAPP_SESSION_MINUTES) and cleared after that."""
    __tablename__ = "whatsapp_conversations"

    id: str = Field(primary_key=True)          # HMAC hash of the sender's number
    updated_at: datetime = Field(default_factory=_now, index=True)
    lang: str = "ar"
    history: str = "[]"                        # recent turns (JSON), redacted
    pending: Optional[str] = None              # JSON: an escalation waiting for the visitor's consent
    demo: bool = False                         # from the staff simulator


class ChatEvent(SQLModel, table=True):
    """One row per chat message, for the staff overview. No message text and no personal
    data: only when, which language, what the agent did, and what the visitor did next."""
    __tablename__ = "chat_events"

    id: str = Field(default_factory=lambda: str(uuid4()), primary_key=True)
    at: datetime = Field(default_factory=_now, index=True)
    lang: str                                  # ar | en
    action: str = Field(index=True)            # answer | recommend | escalate | verify
    from_faq: bool = False                     # the answer cites an FAQ entry
    sourced: bool = False                      # the answer cites at least one approved source
    tier_id: Optional[str] = None              # recommended tier, if any
    register_clicked: bool = False             # visitor opened the registration page from the tier card
    case_created: bool = False                 # an escalation the visitor sent on to support
    channel: str = Field(default="web", index=True)  # web | whatsapp
    demo: bool = False                         # generated by app.seed_demo


class UnansweredQuestion(SQLModel, table=True):

    """Questions the agent escalated, grouped by normalized text for the staff dashboard."""
    __tablename__ = "unanswered_questions"

    id: str = Field(default_factory=lambda: str(uuid4()), primary_key=True)
    key: str = Field(index=True, unique=True)
    question: str
    count: int = 1
    first_seen: datetime = Field(default_factory=_now)
    last_seen: datetime = Field(default_factory=_now, index=True)
    resolved: bool = Field(default=False, index=True)


class FaqCategory(SQLModel, table=True):
    __tablename__ = "faq_categories"

    id: str = Field(primary_key=True)          # stable slug, e.g. "memberships"
    title_ar: str
    title_en: str
    position: int = 0


class FaqItem(SQLModel, table=True):
    """One FAQ entry. Seeded from data/faq.json, then added to by staff."""
    __tablename__ = "faq_items"

    id: str = Field(default_factory=lambda: str(uuid4()), primary_key=True)
    created_at: datetime = Field(default_factory=_now, index=True)
    category_id: str = Field(foreign_key="faq_categories.id", index=True)
    question_ar: Optional[str] = None
    question_en: Optional[str] = None
    answer_ar: Optional[str] = None
    answer_en: Optional[str] = None
    source_title: str
    source_title_en: Optional[str] = None
    source_url: Optional[str] = None
    checked_at: date
    demo: bool = True                          # not yet approved by the association
    unanswered_id: Optional[str] = None        # set when promoted from an unanswered question


class OtpChallenge(SQLModel, table=True):
    """A pending verification code. Neither the code nor the phone/email is stored in
    plain text: both are HMAC hashes. Rows are deleted on success and after a day."""
    __tablename__ = "otp_challenges"

    id: str = Field(default_factory=lambda: str(uuid4()), primary_key=True)
    target_hash: str = Field(index=True)
    channel: str
    code_hash: str
    created_at: datetime = Field(default_factory=_now, index=True)
    expires_at: datetime
    attempts: int = 0


class StaffUser(SQLModel, table=True):
    """A staff account. Passwords are stored as scrypt hashes only."""
    __tablename__ = "staff_users"

    id: str = Field(default_factory=lambda: str(uuid4()), primary_key=True)
    created_at: datetime = Field(default_factory=_now)
    email: str = Field(index=True, unique=True)   # lower-case
    name: str                                    # shown in the action log and as "replied by" (staff only)
    role: str = "staff"                          # admin (also manages accounts) | staff
    password_hash: str = ""
    active: bool = True
    must_change_password: bool = False           # set when an admin creates or resets the password
    last_login_at: Optional[datetime] = None
    demo: bool = False                           # created by app.seed_demo


class StaffSession(SQLModel, table=True):
    """A signed-in browser. Only a hash of the session token is stored."""
    __tablename__ = "staff_sessions"

    id: str = Field(default_factory=lambda: str(uuid4()), primary_key=True)
    token_hash: str = Field(index=True, unique=True)
    user_id: str = Field(index=True)
    created_at: datetime = Field(default_factory=_now)
    expires_at: datetime
    revoked: bool = False


class AuditEntry(SQLModel, table=True):
    """Who did what and when in the staff dashboard (idea 66)."""
    __tablename__ = "audit_log"

    id: str = Field(default_factory=lambda: str(uuid4()), primary_key=True)
    at: datetime = Field(default_factory=_now, index=True)
    actor: str = ""                      # staff account name (or the name typed with the shared token)
    actor_id: Optional[str] = Field(default=None, index=True)  # staff account id; empty for the shared token
    action: str = Field(index=True)      # e.g. faq.promote, faq.update, faq.delete, case.status, export.cases
    target_type: str = ""
    target_id: str = Field(default="", index=True)
    summary: str = ""


_connect_args = {"check_same_thread": False} if DATABASE_URL.startswith("sqlite") else {}
engine = create_engine(DATABASE_URL, connect_args=_connect_args)


# ---------- Schema: Alembic migrations (migrations/versions) ----------
# Change a model, then: alembic revision --autogenerate -m "what changed"  (review the file),
# and the app applies it at the next start. tests/test_migrations.py fails if a model change
# has no migration.
_ROOT = Path(__file__).resolve().parent.parent
BASELINE = "0001"

# Columns that pre-migration databases (made by create_all) may lack, added before they are
# adopted at the baseline. Frozen: new columns go in migrations, never here.
_LEGACY_COLUMNS = {
    "faq_items": {"source_title_en": "VARCHAR"},
    "audit_log": {"actor_id": "VARCHAR"},
    "support_cases": {"category": "VARCHAR DEFAULT 'inquiry'", "tracking_hash": "VARCHAR DEFAULT ''",
                      "reply": "VARCHAR", "replied_at": "TIMESTAMP", "replied_by": "VARCHAR",
                      "demo": "BOOLEAN DEFAULT FALSE"},
}


def alembic_config(connection=None):
    from alembic.config import Config
    cfg = Config(str(_ROOT / "alembic.ini"))
    cfg.set_main_option("script_location", str(_ROOT / "migrations"))
    cfg.attributes["configure_logger"] = False  # keep the app's logging as it is
    if connection is not None:
        cfg.attributes["connection"] = connection
    return cfg


def _adopt_legacy(conn) -> None:
    """A database from before migrations: add the columns it may lack. The baseline migration
    then creates only the tables it doesn't have."""
    inspector = inspect(conn)
    for table, columns in _LEGACY_COLUMNS.items():
        if not inspector.has_table(table):
            continue
        existing = {c["name"] for c in inspector.get_columns(table)}
        for name, sql_type in columns.items():
            if name not in existing:
                conn.execute(text(f"ALTER TABLE {table} ADD COLUMN {name} {sql_type}"))


def schema_version(conn) -> str | None:
    from alembic.runtime.migration import MigrationContext
    return MigrationContext.configure(conn).get_current_revision()


def init_db(bind=None) -> None:
    """Brings the database to the latest migration: creates it if empty, adopts a pre-migration
    database, or applies the migrations it hasn't had yet. `bind`: another engine (tests)."""
    from alembic import command
    with (bind or engine).begin() as conn:
        if schema_version(conn) is None and inspect(conn).has_table("support_cases"):
            _adopt_legacy(conn)
        command.upgrade(alembic_config(conn), "head")


def get_session():
    with Session(engine) as session:
        yield session
