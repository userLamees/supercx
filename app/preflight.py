"""Go-live check: what is live, what is demo, and what must be fixed before real users.

    python -m app.preflight            # report; exit code 1 if something blocks going live
    python -m app.preflight --secrets  # print fresh random values to paste into Replit Secrets

The app also logs the blocking problems at startup (main.py), so they show in Replit's console.
Never prints a secret's value (except the new ones generated by --secrets).
"""
import secrets
import sys

from sqlmodel import Session

from . import config
from .db import engine, init_db


def problems() -> list[str]:
    """Things that block a real launch. Empty when ready (demo connectors are allowed)."""
    found = []
    if config.ON_REPLIT and engine.dialect.name == "sqlite":
        found.append("DATABASE_URL: Replit is using SQLite, which is not kept between deployments. "
                     "Add Replit Postgres (it sets DATABASE_URL).")
    if not config.OTP_SECRET:
        found.append("OTP_SECRET: not set; pending verification codes are lost on every restart.")
    if not (config.STAFF_ADMIN_EMAIL and config.STAFF_ADMIN_PASSWORD) and not config.SUPPORT_TOKEN:
        found.append("STAFF_ADMIN_EMAIL / STAFF_ADMIN_PASSWORD (or SUPPORT_TOKEN): no way for staff to sign in.")
    if config.SUPPORT_TOKEN and len(config.SUPPORT_TOKEN) < 24:
        found.append("SUPPORT_TOKEN: shorter than 24 characters; use a long random value.")
    if config.ON_REPLIT and not config.PUBLIC_BASE_URL:
        found.append("PUBLIC_BASE_URL: unknown; links in notifications may be wrong.")
    return found


def new_secrets() -> dict[str, str]:
    return {
        "SUPPORT_TOKEN": secrets.token_urlsafe(32),
        "OTP_SECRET": secrets.token_hex(32),
        "CASE_WEBHOOK_SECRET": secrets.token_hex(32),
        "STAFF_ADMIN_PASSWORD": f"Cx-{secrets.token_urlsafe(12)}",
    }


def main(argv: list[str]) -> int:
    if "--secrets" in argv:
        print("Paste these into Replit → Secrets (each value is new and random; keep them private):\n")
        for key, value in new_secrets().items():
            print(f"{key}={value}")
        print("\nSTAFF_ADMIN_PASSWORD is temporary: the first admin must change it at first sign-in.")
        return 0

    from .integrations.status import report
    init_db()  # brings the schema up to date, as the app does at startup
    with Session(engine) as session:
        items = report(session)
    marks = {"live": "LIVE   ", "demo": "demo   ", "off": "off    ", "missing": "MISSING"}
    print(f"SuperCX preflight · {'Replit' if config.ON_REPLIT else 'local'} · database: {engine.dialect.name}\n")
    for item in items:
        line = f"  {marks[item['state']]}  {item['key']:<16} {item['detail']}"
        if item["state"] != "live":
            line += f"   needs: {', '.join(item['needs'])}"
        print(line)
    blocking = problems()
    print()
    if blocking:
        print("Fix before going live:")
        for p in blocking:
            print(f"  - {p}")
        return 1
    print("Ready to go live. Demo items keep working with demo data until their settings are added.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
